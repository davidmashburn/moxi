def ink(label, x, y):
    """Yield the lit pixels of a single-line label at its top-left corner."""
    for index, character in enumerate(label):
        rows = ROWS.get(character, ROWS["?"])
        for row in range(7):
            bits = rows >> (8 * (6 - row))
            for col in range(5):
                if bits & (16 >> col):
                    yield x + index * 7 + col, y + row
