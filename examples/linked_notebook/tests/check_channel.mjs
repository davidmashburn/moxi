import assert from 'node:assert/strict';
import {Channel,Kind,Protocol} from '../moxi_linked_notebook/widget.mjs';
let now=0,receive,acks=0,failures=0;
const sent=[],model={on:(_,f)=>receive=f,off:(_,f)=>assert.equal(f,receive),send:m=>sent.push(m)};
const identity={session:'session',generation:2,view:'view'};
const c=new Channel(model,identity,{now:()=>now,ack:()=>acks++,fail:()=>failures++});
c.send(Kind.hello);
for(let i=0;i<10000;i++)c.queue({selected:i%64,minimum:0,finals:i+1,dataVersion:1});
assert.equal(sent.length,1);assert.equal(c.metrics.maxQueued,2);assert.equal(c.pending.finals,10000);
for(const patch of [{session:'old'},{generation:1},{view:'other'},{v:2},{seq:99},{kind:'unknown'}])receive({...sent[0],kind:Kind.ack,...patch});
assert.equal(acks,0);now=100;receive({...sent[0],kind:Kind.ack});
assert.equal(sent.length,2);assert.equal(sent[1].state.finals,10000);assert.equal(c.pending,null);
receive({...sent[1],kind:Kind.ack});assert.equal(acks,2);
now=1000;c.tick();assert.equal(sent.at(-1).kind,Kind.ping);
now+=Protocol.timeoutMs+1;c.tick();assert.equal(failures,1);assert.equal(c.flight,null);
c.send(Kind.hello);receive({...sent.at(-1),kind:Kind.error,detail:'failure'});assert.equal(failures,2);
c.dispose();const count=sent.length;c.queue({});c.tick();c.send(Kind.hello);assert.equal(sent.length,count);
assert(c.metrics.roundtripMs.length<=120);assert(c.metrics.bytes.every(n=>n<=4096));
console.log(JSON.stringify({updates:10000,maxQueued:c.metrics.maxQueued,coalesced:c.metrics.coalesced,finals:10000,staleRejected:true,timeout:true,dispose:true}));
