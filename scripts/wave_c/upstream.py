PIN = '3fd5a7e7c622d6130c99a290b88c4fee039deab2'
CANVAS_PIN = '58fb12a471a65dfbc29ebc743860448439a6af22'
REPOSITORY = 'https://github.com/randyzwitch/dataviz_mojo'


def pinned_inventory(checkout):
    """Inspect the original clean pin; publish only repository-relative paths."""
    checkout = checkout.resolve()
    revision = subprocess.check_output(['git', '-C', str(checkout), 'rev-parse', 'HEAD'], text=True).strip()
    if revision != PIN:
        raise ValueError(f'upstream pin mismatch: {revision}')
    if subprocess.check_output(['git', '-C', str(checkout), 'status', '--porcelain'], text=True).strip():
        raise ValueError('upstream must be clean')
    lock = checkout / 'pixi.lock'
    if CANVAS_PIN not in lock.read_text():
        raise ValueError('reference Canvas pin mismatch')
    paths = subprocess.check_output(['git', '-C', str(checkout), 'ls-files', '-z', '--', 'dataviz'], text=True).split('\0')
    inventory = {}
    matches = []
    for name in sorted(name for name in paths if name.endswith('.mojo')):
        content = (checkout / name).read_bytes()
        inventory[name] = hashlib.sha256(content).hexdigest()
        if 'tricontour' in name.lower() or b'tricontour' in content.lower():
            matches.append(name)
    if not inventory:
        raise ValueError('pinned dataviz Mojo inventory is empty')
    if matches:
        raise ValueError('reference tricontour availability changed; inspect before claiming a missing gate')
    inventory_sha = hashlib.sha256(json.dumps(inventory, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return dict(repository=REPOSITORY, revision=revision, dirty=False,
                canvas_revision=CANVAS_PIN, lock_sha256=hashlib.sha256(lock.read_bytes()).hexdigest(),
                inventory=inventory, inventory_sha256=inventory_sha, mojo_files=len(inventory),
                query='case-insensitive tricontour in tracked dataviz/**/*.mojo paths and contents',
                matching_files=matches, tricontour_available=False)


